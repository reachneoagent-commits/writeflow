const lang = 'en';

export function getLang() { return lang; }

// The interface is English only; kept so existing callers keep working.
export function setLang() { apply(); }

// {name} is replaced by variables; values are not HTML-escaped, callers pass numbers or already-escaped text.
export function t(key, vars) {
  let s = DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function apply(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
}
